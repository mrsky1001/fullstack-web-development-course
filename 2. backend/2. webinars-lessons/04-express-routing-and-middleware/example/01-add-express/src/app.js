/**
 * ====================================================================
 * УРОК 2: НАСТРОЙКА EXPRESS.JS - ПРИЛОЖЕНИЕ (app.js)
 * ====================================================================
 * 
 * Этот файл отвечает за КОНФИГУРАЦИЮ Express приложения.
 * Мы отделяем его от server.js для лучшей организации кода.
 * 
 * Разделение на app.js и server.js — это хорошая практика:
 * - app.js — настройка Express (маршруты, middleware)
 * - server.js — запуск сервера (только listen)
 * 
 * Это упрощает тестирование и позволяет переиспользовать app.
 * ====================================================================
 */

// ШАГ 1: Подключаем Express
// --------------------------------------------------------------------
// Express — это фреймворк для Node.js, упрощающий создание веб-серверов.
// Он берёт на себя много рутинной работы (парсинг, маршрутизация).

const express = require('express');

// ШАГ 2: Создаём экземпляр Express приложения
// --------------------------------------------------------------------
// Функция express() возвращает объект приложения.
// По соглашению его называют 'app' или 'server'.

const app = express();

// ШАГ 3: Настраиваем встроенные middleware
// --------------------------------------------------------------------
// Middleware — это функции, которые обрабатывают запрос ПЕРЕД маршрутами.
// 
// express.json() — автоматически парсит JSON в req.body
// express.urlencoded() — парсит данные HTML форм

app.use(express.json());
app.use(express.urlencoded({ extended: true }));

// ШАГ 4: Определяем маршруты (Routes)
// --------------------------------------------------------------------
// В Express маршруты определяются проще, чем в "чистом" Node.js.
// Формат: app.МЕТОД(путь, обработчик)
// 
// Методы: get, post, put, delete, patch, options, all

// 4.1 Главная страница localhost:3000/
app.get('/', (req, res) => {
    // res.send() автоматически:
    // - Определяет Content-Type по типу данных
    // - Устанавливает Content-Length
    // - Завершает ответ (не нужен res.end())

    res.send(`
        <h1>🚀 Express.js приложение</h1>
        <p>Сервер работает с использованием Express!</p>
        <h3>Доступные маршруты:</h3>
        <ul>
            <li><a href="/about">О проекте</a> (GET)</li>
            <li><a href="/api/status">Статус API</a> (GET)</li>
            <li><a href="/api/products">Список товаров</a> (GET)</li>
        </ul>
    `);
});

// 4.2 Страница "О проекте"
app.get('/about', (req, res) => {
    res.send(`
        <h1>📚 О проекте</h1>
        <p>Это урок 2 курса Full-Stack Web Development.</p>
        <p>В этом уроке мы изучаем фреймворк Express.js.</p>
        <p><a href="/">← На главную</a></p>
    `);
});

// 4.3 API: Статус сервера (JSON)
app.get('/api/status', (req, res) => {
    // res.json() — специальный метод для отправки JSON
    // Он автоматически устанавливает Content-Type: application/json

    res.json({
        status: 'success',
        message: 'Сервер работает на Express.js!',
        framework: 'Express 4.x',
        timestamp: new Date().toISOString()
    });
});

// 4.4 API: Список товаров (заготовка для будущих уроков)
app.get('/api/products', (req, res) => {
    // Пока возвращаем статический массив
    // В будущих уроках данные будут из базы данных

    const products = [
        { id: 1, name: 'Intel Core i9-13900K', price: 55990, category: 'Процессоры' },
        { id: 2, name: 'AMD Ryzen 9 7950X', price: 62990, category: 'Процессоры' },
        { id: 3, name: 'NVIDIA GeForce RTX 4090', price: 159990, category: 'Видеокарты' }
    ];

    res.json({
        status: 'success',
        data: products,
        count: products.length
    });
});

// 4.5 Обработка несуществующих маршрутов (404)
// --------------------------------------------------------------------
// ВАЖНО: Этот обработчик должен быть ПОСЛЕДНИМ!
// app.use() без пути срабатывает на ВСЕ запросы, которые не подошли выше.

app.use((req, res) => {
    res.status(404).json({
        status: 'error',
        message: `Маршрут ${req.method} ${req.url} не найден`,
        statusCode: 404
    });
});

// ШАГ 5: Экспортируем приложение
// --------------------------------------------------------------------
// module.exports позволяет использовать app в других файлах (server.js)

module.exports = app;
