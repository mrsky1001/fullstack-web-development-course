/**
 * ====================================================================
 * УРОК 2: НАСТРОЙКА EXPRESS.JS - ЗАПУСК СЕРВЕРА (server.js)
 * ====================================================================
 * 
 * Этот файл отвечает ТОЛЬКО за запуск сервера.
 * Вся конфигурация Express находится в app.js (разделение ответственности).
 * 
 * ====================================================================
 */

// ШАГ 1: Импортируем настроенное Express приложение
// --------------------------------------------------------------------
// './' означает "из текущей папки"
// Расширение .js можно не указывать

const app = require('./app');

// ШАГ 2: Определяем порт
// --------------------------------------------------------------------
// process.env.PORT — переменная окружения (если задана системой)
// По умолчанию используем 3000

const PORT = process.env.PORT || 3000;

// ШАГ 3: Запускаем сервер
// --------------------------------------------------------------------
// app.listen() — метод Express, который запускает HTTP сервер
// Внутри он использует тот же http.createServer(), что и в Уроке 1

app.listen(PORT, () => {
    console.log('');
    console.log('====================================================');
    console.log('  🎓 УРОК 2: EXPRESS.JS ПРИЛОЖЕНИЕ');
    console.log('====================================================');
    console.log(`  ✅ Сервер успешно запущен!`);
    console.log(`  📍 Адрес: http://localhost:${PORT}`);
    console.log('');
    console.log('  Доступные маршруты:');
    console.log(`    • GET  /              - Главная страница`);
    console.log(`    • GET  /about         - О проекте`);
    console.log(`    • GET  /api/status    - Статус API`);
    console.log(`    • GET  /api/products  - Список товаров`);
    console.log('');
    console.log('  💡 Совет: используйте npm run dev для auto-reload');
    console.log('  Для остановки: Ctrl + C');
    console.log('====================================================');
    console.log('');
});
