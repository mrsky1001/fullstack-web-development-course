// Массив строк — пронумерованный список типов помещений
const roomTypes = ['Офис', 'Переговорная', 'Конференц-зал', 'Опенспейс'];

console.log('Все типы комнат в массиве:', roomTypes);

// Обращение к элементам по их порядковому номеру (индексу с 0):
console.log('Первый элемент [0]:', roomTypes[0]);
console.log('Второй элемент [1]:', roomTypes[1]);

// Длина массива (свойство length):
console.log('Всего элементов в списке:', roomTypes.length);
