// Массив — это упорядоченный список значений в квадратных скобках []:
const roomNames = ['Мини-офис Focus', 'Конференц-зал Alpha', 'Опенспейс Hub'];

console.log('Список всех комнат:', roomNames);
console.log('Первая комната в массиве (индекс 0):', roomNames[0]);
console.log('Всего комнат в массиве (длина .length):', roomNames.length);
