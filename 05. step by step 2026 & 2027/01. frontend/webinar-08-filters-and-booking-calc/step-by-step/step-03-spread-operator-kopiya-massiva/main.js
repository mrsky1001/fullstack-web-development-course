// Шаг 3: Спред-оператор [...] для копирования массива
// Теория по этой теме подробно описана в файле README.md в этой папке.

const original = ['Фокус', 'Альфа', 'Хаб'];

// Создаем независимую копию через три точки [...]:
const copy = [...original];

// Меняем только копию:
copy.push('Новая комната');

console.log('Оригинал остался неизменным:', original);
console.log('Копия изменилась:', copy);
