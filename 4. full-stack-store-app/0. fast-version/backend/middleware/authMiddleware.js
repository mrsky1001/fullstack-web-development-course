// Функция-middleware: проверяет, авторизован ли пользователь
// Если в сессии есть user_id — пропускаем дальше
// Если нет — возвращаем ошибку 401 (Unauthorized)
function authMiddleware(req, res, next) {
  if (req.session && req.session.user_id) {
    // Пользователь авторизован — пропускаем к следующему обработчику
    next();
  } else {
    // Пользователь НЕ авторизован — возвращаем ошибку
    res.status(401).json({ error: 'Необходимо авторизоваться' });
  }
}

module.exports = authMiddleware;
