const mysql = require('mysql2');

// Создаём пул подключений к MySQL с промисами
// Пул позволяет переиспользовать соединения (эффективнее)
const pool = mysql.createPool({
  host: 'localhost',       // Адрес сервера MySQL
  user: 'root',            // Имя пользователя MySQL
  password: 'admin',            // Пароль (пустой для локальной разработки)
  database: 'techparts',   // Имя базы данных из ТЗ
  charset: 'utf8mb4'       // Кодировка для кириллицы
});

// Экспортируем пул с промисами для async/await
module.exports = pool.promise();
